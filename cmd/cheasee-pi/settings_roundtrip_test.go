// fullSchema is the canonical scaffold output with the new /opt/cheasee-pi
// resource paths and the extended schema (extensions/theme/sessionDir).
var fullSchema = &Settings{
	Comment:         "Generated by cheasee-pi init. Edit this file to configure your pi environment.",
	DefaultProvider: "opencode-go",
	DefaultModel:    "gpt-4o",
	Docker:          DockerSettings{Memory: "4G", CPUs: "4.0"},
	GitIdentity:     GitIdentitySettings{Name: "Test User", Email: "test@example.com"},
	Skills:          []string{"/opt/cheasee-pi/.pi/skills", "bash", "web"},
	Prompts:         []string{"/opt/cheasee-pi/.pi/prompts", "code-review"},
	Extensions:      []string{"/opt/cheasee-pi/.pi/extensions"},
	Theme:           "cheasee-pi",
	SessionDir:      ".pi/sessions",
}

// ──────────────────────────────────────────────
// Save → Load round-trip (adapter)
// ──────────────────────────────────────────────

func TestSettingsRoundTrip_fullSchemaSurvives(t *testing.T) {
	workdir := t.TempDir()
	if err := fullSchema.Save(workdir); err != nil {
		t.Fatalf("Save failed: %v", err)
	}

	loaded, err := LoadSettings(workdir)
	if err != nil {
		t.Fatalf("Load failed: %v", err)
	}

	if loaded.Comment != fullSchema.Comment {
		t.Errorf("Comment = %q, want %q", loaded.Comment, fullSchema.Comment)
	}
	if loaded.DefaultProvider != fullSchema.DefaultProvider {
		t.Errorf("DefaultProvider = %q, want %q", loaded.DefaultProvider, fullSchema.DefaultProvider)
	}
	if loaded.DefaultModel != fullSchema.DefaultModel {
		t.Errorf("DefaultModel = %q, want %q", loaded.DefaultModel, fullSchema.DefaultModel)
	}
	if loaded.Docker != fullSchema.Docker {
		t.Errorf("Docker = %+v, want %+v", loaded.Docker, fullSchema.Docker)
	}
	if loaded.GitIdentity != fullSchema.GitIdentity {
		t.Errorf("GitIdentity = %+v, want %+v", loaded.GitIdentity, fullSchema.GitIdentity)
	}
	if len(loaded.Skills) != len(fullSchema.Skills) || loaded.Skills[0] != fullSchema.Skills[0] {
		t.Errorf("Skills = %v, want %v", loaded.Skills, fullSchema.Skills)
	}
	if len(loaded.Prompts) != len(fullSchema.Prompts) || loaded.Prompts[0] != fullSchema.Prompts[0] {
		t.Errorf("Prompts = %v, want %v", loaded.Prompts, fullSchema.Prompts)
	}
	if len(loaded.Extensions) != len(fullSchema.Extensions) || loaded.Extensions[0] != fullSchema.Extensions[0] {
		t.Errorf("Extensions = %v, want %v", loaded.Extensions, fullSchema.Extensions)
	}
	if loaded.Theme != fullSchema.Theme {
		t.Errorf("Theme = %q, want %q", loaded.Theme, fullSchema.Theme)
	}
	if loaded.SessionDir != fullSchema.SessionDir {
		t.Errorf("SessionDir = %q, want %q", loaded.SessionDir, fullSchema.SessionDir)
	}
}

func TestSettingsSave_byteStable(t *testing.T) {
	workdir := t.TempDir()
	if err := fullSchema.Save(workdir); err != nil {
		t.Fatalf("first Save failed: %v", err)
	}
	first, err := os.ReadFile(filepath.Join(workdir, ".pi", "settings.json"))
	if err != nil {
		t.Fatal(err)
	}

	if err := fullSchema.Save(workdir); err != nil {
		t.Fatalf("second Save failed: %v", err)
	}
	second, err := os.ReadFile(filepath.Join(workdir, ".pi", "settings.json"))
	if err != nil {
		t.Fatal(err)
	}

	if string(first) != string(second) {
		t.Errorf("repeated Save must be byte-identical:\nfirst:  %q\nsecond: %q", first, second)
	}
}

func TestSettingsSave_htmlSafe(t *testing.T) {
	s := &Settings{
		Skills:  []string{"use <b>bold</b> & <i>italic</i> in output"},
		Prompts: []string{"a > b"},
	}
	workdir := t.TempDir()
	if err := s.Save(workdir); err != nil {
		t.Fatalf("Save failed: %v", err)
	}

	data, err := os.ReadFile(filepath.Join(workdir, ".pi", "settings.json"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(data), `\u003c`) || strings.Contains(string(data), `\u003e`) || strings.Contains(string(data), `\u0026`) {
		t.Errorf("Save HTML-escaped <>&: %s", data)
	}
	if !strings.Contains(string(data), "<b>bold</b>") {
		t.Errorf("skills entry must survive byte-identical, got: %s", data)
	}
}
