func TestSetDefaultProvider_setsBothFields(t *testing.T) {
	s := &Settings{}
	s.SetDefaultProvider("openai", "gpt-4o")
	if s.DefaultProvider != "openai" {
		t.Errorf("DefaultProvider = %q, want openai", s.DefaultProvider)
	}
	if s.DefaultModel != "gpt-4o" {
		t.Errorf("DefaultModel = %q, want gpt-4o", s.DefaultModel)
	}
}

func TestSetDefaultProvider_emptyModelKeepsExisting(t *testing.T) {
	s := &Settings{DefaultModel: "gpt-4o-mini"}
	s.SetDefaultProvider("openai", "")
	if s.DefaultProvider != "openai" {
		t.Errorf("DefaultProvider = %q, want openai", s.DefaultProvider)
	}
	if s.DefaultModel != "gpt-4o-mini" {
		t.Errorf("empty model must leave DefaultModel untouched, got %q", s.DefaultModel)
	}
}

func TestSetDefaultProvider_chains(t *testing.T) {
	s := (&Settings{}).SetDefaultProvider("openai", "gpt-4o")
	if s.DefaultProvider != "openai" {
		t.Errorf("chained SetDefaultProvider must return receiver, got %q", s.DefaultProvider)
	}
}

