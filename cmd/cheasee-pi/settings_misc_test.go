// TestSettingsScaffold_PreservesParentPathEntries asserts that `../private-pi/...`
// skills/prompts entries survive init — nothing strips them anymore (the old

func TestSettingsScaffold_PreservesParentPathEntries(t *testing.T) {
	workdir := t.TempDir()
	s := &Settings{
		Comment: "keep me",
		Skills:  []string{"../private-pi/skills", "bash"},
		Prompts: []string{"../private-pi/prompts", "code-review"},
	}
	if err := s.Save(workdir); err != nil {
		t.Fatal(err)
	}

	// Scaffold is idempotent: existing settings.json is left untouched.
	if err := (&templateSettingsRenderer{source: embeddedFS, templatePath: "embedded/pi/settings.json", dest: func(workdir string) string { return filepath.Join(workdir, ".pi", "settings.json") }}).Scaffold(context.Background(), workdir, TemplateSettingsValues{}); err != nil {
		t.Fatalf("scaffold: %v", err)
	}

	loaded, err := LoadSettings(workdir)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Contains(loaded.Skills, "../private-pi/skills") {
		t.Errorf("Skills lost parent-path entry: %v", loaded.Skills)
	}
	if !slices.Contains(loaded.Prompts, "../private-pi/prompts") {
		t.Errorf("Prompts lost parent-path entry: %v", loaded.Prompts)
	}
	if loaded.Comment != "keep me" {
		t.Errorf("comment must survive: %q", loaded.Comment)
	}
}

// ──────────────────────────────────────────────
// Scaffold → typed Settings (template.go proof)
// ──────────────────────────────────────────────

func TestSettingsScaffold_outputLoadsAsTypedSettings(t *testing.T) {
	workdir := ScaffoldSettings(t, TemplateSettingsValues{
		Provider: "opencode-go",
		GitName:  "Test User",
		GitEmail: "test@example.com",
		Memory:   "4G",
		CPUs:     "4.0",
	})

	s, err := LoadSettings(workdir)
	if err != nil {
		t.Fatalf("scaffold output must load via LoadSettings: %v", err)
	}
	if s.DefaultProvider != "opencode-go" || s.DefaultModel != "gpt-4o" {
		t.Errorf("provider/model mismatch: %+v", s)
	}
	if s.Docker != (DockerSettings{Memory: "4G", CPUs: "4.0"}) {
		t.Errorf("docker mismatch: %+v", s.Docker)
	}
	if s.GitIdentity != (GitIdentitySettings{Name: "Test User", Email: "test@example.com"}) {
		t.Errorf("gitIdentity mismatch: %+v", s.GitIdentity)
	}
	if !strings.Contains(s.Comment, "Generated by cheasee-pi init") {
		t.Errorf("// comment key must be present in scaffold output, got %q", s.Comment)
	}
	if _, err := os.Stat(filepath.Join(workdir, ".pi", "settings.json") + ".tmp"); !os.IsNotExist(err) {
		t.Error("no .tmp residue after Scaffold")
	}
}

