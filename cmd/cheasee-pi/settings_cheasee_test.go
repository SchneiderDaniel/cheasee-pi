// ──────────────────────────────────────────────
// CheaseeSettings schema (dedicated settings file)
// ──────────────────────────────────────────────

// fullCheaseeSchema is the canonical cheasee-settings.json content.
var fullCheaseeSchema = &CheaseeSettings{
	Comment:         "Generated by cheasee-pi init. Edit this file to configure your cheasee-pi environment.",
	DefaultProvider: "opencode-go",
	Docker:          DockerSettings{Memory: "4G", CPUs: "4.0"},
	GitIdentity:     GitIdentitySettings{Name: "Test User", Email: "test@example.com"},
	OAuth:           OAuthSettings{ClientID: "test-client"},
	Repository:      &RepositorySettings{URL: "https://github.com/owner/repo.git", User: "octocat"},
}

func TestCheaseeSettings_roundTrip(t *testing.T) {
	workdir := t.TempDir()
	if err := fullCheaseeSchema.Save(workdir); err != nil {
		t.Fatalf("Save failed: %v", err)
	}

	loaded, err := LoadCheaseeSettings(workdir)
	if err != nil {
		t.Fatalf("Load failed: %v", err)
	}
	// Repository is a pointer (omitempty for the legacy no-github output), so
	// compare values rather than struct equality.
	if !reflect.DeepEqual(loaded, fullCheaseeSchema) {
		t.Errorf("round-trip mismatch:\n got %+v\nwant %+v", loaded, fullCheaseeSchema)
	}
}

func TestCheaseeSettings_nilRepositoryOmitsSection(t *testing.T) {
	// Legacy/no-github output: {} loads with nil Repository, and a typed Save
	// must not emit a repository key (omitempty, section-free legacy output).
	workdir := t.TempDir()
	testutil.WriteCheaseeSettingsFile(t, workdir, `{}`)
	s, err := LoadCheaseeSettings(workdir)
	if err != nil {
		t.Fatal(err)
	}
	if s.Repository != nil {
		t.Fatalf("empty {} must load with nil Repository, got %+v", s.Repository)
	}
	if err := s.Save(workdir); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(cheaseeSettingsPath(workdir))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(data), "repository") {
		t.Errorf("Save of nil Repository must not emit a repository key, got: %s", data)
	}
}

func TestCheaseeSettings_saveByteStable(t *testing.T) {
	workdir := t.TempDir()
	if err := fullCheaseeSchema.Save(workdir); err != nil {
		t.Fatalf("first Save failed: %v", err)
	}
	first, err := os.ReadFile(cheaseeSettingsPath(workdir))
	if err != nil {
		t.Fatal(err)
	}
	if err := fullCheaseeSchema.Save(workdir); err != nil {
		t.Fatalf("second Save failed: %v", err)
	}
	second, err := os.ReadFile(cheaseeSettingsPath(workdir))
	if err != nil {
		t.Fatal(err)
	}
	if string(first) != string(second) {
		t.Errorf("repeated Save must be byte-identical:\nfirst:  %q\nsecond: %q", first, second)
	}
}

func TestLoadCheaseeSettings_failureModes(t *testing.T) {
	t.Run("missing file", func(t *testing.T) {
		_, err := LoadCheaseeSettings(t.TempDir())
		if !errors.Is(err, os.ErrNotExist) {
			t.Fatalf("missing file: want os.ErrNotExist, got %v", err)
		}
	})
	t.Run("corrupt JSON", func(t *testing.T) {
		workdir := t.TempDir()
		testutil.WriteCheaseeSettingsFile(t, workdir, "{invalid")
		if _, err := LoadCheaseeSettings(workdir); err == nil {
			t.Fatal("corrupt JSON must be a hard error")
		}
	})
	t.Run("type mismatch", func(t *testing.T) {
		workdir := t.TempDir()
		testutil.WriteCheaseeSettingsFile(t, workdir, `{"docker": {"memory": 4096}}`)
		if _, err := LoadCheaseeSettings(workdir); err == nil {
			t.Fatal("type mismatch must be a hard error")
		}
	})
	t.Run("non-object", func(t *testing.T) {
		workdir := t.TempDir()
		testutil.WriteCheaseeSettingsFile(t, workdir, `[1,2]`)
		if _, err := LoadCheaseeSettings(workdir); err == nil {
			t.Fatal("non-object JSON must be a hard error")
		}
	})
	t.Run("null JSON", func(t *testing.T) {
		// null unmarshals cleanly into both the typed struct and the raw map
		// (leaving the map nil) — it must be a hard error, not an empty schema
		// a later Save would silently overwrite.
		workdir := t.TempDir()
		testutil.WriteCheaseeSettingsFile(t, workdir, `null`)
		if _, err := LoadCheaseeSettings(workdir); err == nil {
			t.Fatal("null JSON must be a hard error")
		}
	})
	t.Run("empty object zero value", func(t *testing.T) {
		workdir := t.TempDir()
		testutil.WriteCheaseeSettingsFile(t, workdir, `{}`)
		s, err := LoadCheaseeSettings(workdir)
		if err != nil {
			t.Fatalf("empty {} must load, got %v", err)
		}
		if s.DefaultProvider != "" || s.Docker.Memory != "" || s.OAuth.ClientID != "" {
			t.Errorf("empty {} must yield the zero value, got %+v", s)
		}
	})
}
