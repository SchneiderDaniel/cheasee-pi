func TestRebuildUI_BuildsAndAppliesOnlyUI(t *testing.T) {
	resetBuildState(t)
	buildNoDockerCheck = true
	t.Setenv("XDG_CACHE_HOME", t.TempDir())
	configHome := t.TempDir()
	t.Setenv("XDG_CONFIG_HOME", configHome)
	authPath := filepath.Join(configHome, "cheasee-pi", "auth.json")
	if err := os.MkdirAll(filepath.Dir(authPath), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(authPath, []byte("{}\n"), 0600); err != nil {
		t.Fatal(err)
	}
	root := buildWorkspaceFixture(t)
	chdir(t, root)

	stub := &buildTestStub{}
	stub.install(t)
	if err := runRebuildUIE(&cobra.Command{}, nil); err != nil {
		t.Fatalf("runRebuildUIE: %v", err)
	}
	if len(stub.compose) != 2 {
		t.Fatalf("expected exactly a UI build and a UI apply, got %d compose calls: %v", len(stub.compose), stub.log)
	}

	buildArgs := stub.composeArgv()
	if len(buildArgs) == 0 || !slices.Equal(buildArgs[len(buildArgs)-1:], []string{"ui"}) || !slices.Contains(buildArgs, "build") {
		t.Errorf("image build must target only ui, got %v", buildArgs)
	}
	applyLog := stub.log[len(stub.log)-1]
	for _, want := range []string{"up -d --no-deps --no-build --pull never ui"} {
		if !strings.Contains(applyLog, want) {
			t.Errorf("container apply must recreate only ui without dependencies, want %q in %q", want, applyLog)
		}
	}
	if !strings.HasSuffix(applyLog, " ui") {
		t.Errorf("apply command must end with only the ui service, got %q", applyLog)
	}
}

func TestRebuildUICmd_Registered(t *testing.T) {
	found := false
	for _, c := range rootCmd.Commands() {
		if c.Name() == "rebuild-ui" {
			found = true
			if c.RunE == nil {
				t.Error("rebuild-ui must use RunE")
			}
			if !c.DisableAutoGenTag {
				t.Error("rebuild-ui must disable the autogenerated tag")
			}
		}
	}
	if !found {
		t.Error("rebuild-ui must be registered on rootCmd")
	}
	if rebuildUICmd.Flags().Lookup("workdir") == nil || rebuildUICmd.Flags().Lookup("no-docker-check") == nil {
		t.Error("rebuild-ui must expose --workdir and --no-docker-check")
	}
}
