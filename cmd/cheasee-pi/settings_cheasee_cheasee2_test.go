package main

import (
	"os"
	"strings"
	"testing"

	"github.com/SchneiderDaniel/cheasee-pi/cmd/cheasee-pi/testutil"
)

func TestCheaseeSettings_bannerKeySurvivesLoadSaveOnce(t *testing.T) {
	workdir := t.TempDir()
	banner := "Generated by cheasee-pi init. Edit this file to configure your cheasee-pi environment."
	testutil.WriteCheaseeSettingsFile(t, workdir, `{"//":"`+banner+`","defaultProvider":"openai"}`)
	s, err := LoadCheaseeSettings(workdir)
	if err != nil {
		t.Fatal(err)
	}
	if err := s.Save(workdir); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(cheaseeSettingsPath(workdir))
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Count(string(data), banner); got != 1 {
		t.Errorf("banner must survive exactly once, got %d occurrences: %s", got, data)
	}
}

// TestCheaseeSettings_saveByteStableWithExtra: a Save carrying non-nil extra
// is byte-stable across repeated saves (alphabetical key order accepted;
// only byte-stability asserted).

func TestCheaseeSettings_saveByteStableWithExtra(t *testing.T) {
	workdir := t.TempDir()
	testutil.WriteCheaseeSettingsFile(t, workdir, `{"defaultProvider":"openai","futureKey":{"nested":true}}`)
	s, err := LoadCheaseeSettings(workdir)
	if err != nil {
		t.Fatal(err)
	}
	if err := s.Save(workdir); err != nil {
		t.Fatalf("first Save: %v", err)
	}
	first, err := os.ReadFile(cheaseeSettingsPath(workdir))
	if err != nil {
		t.Fatal(err)
	}
	if err := s.Save(workdir); err != nil {
		t.Fatalf("second Save: %v", err)
	}
	second, err := os.ReadFile(cheaseeSettingsPath(workdir))
	if err != nil {
		t.Fatal(err)
	}
	if string(first) != string(second) {
		t.Errorf("repeated Save with extra must be byte-identical:\nfirst:  %q\nsecond: %q", first, second)
	}
}

// TestCheaseeSettings_unwritableDirErrorsNoPartialFile: a failed cheasee Save
// must error and leave no partial/target file behind (mirror of
// TestSettingsSave_unwritableDirErrorsNoPartialFile for the cheasee path).

func TestCheaseeSettings_unwritableDirErrorsNoPartialFile(t *testing.T) {
	workdir := t.TempDir()
	if err := os.Chmod(workdir, 0555); err != nil {
		t.Fatal(err)
	}
	defer os.Chmod(workdir, 0755)

	err := (&CheaseeSettings{DefaultProvider: "openai"}).Save(workdir)
	if err == nil {
		t.Fatal("expected error writing into read-only workspace dir, got nil")
	}
	if _, statErr := os.Stat(cheaseeSettingsPath(workdir)); !os.IsNotExist(statErr) {
		t.Error("target file must be absent after failed Save (no partial write)")
	}
}
